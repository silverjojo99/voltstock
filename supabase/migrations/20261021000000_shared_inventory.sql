create table if not exists public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  display_name text not null,
  email text not null,
  created_at timestamptz not null default now()
);

create or replace function public.create_profile_for_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, display_name, email)
  values (
    new.id,
    coalesce(
      nullif(new.raw_user_meta_data ->> 'full_name', ''),
      nullif(new.raw_user_meta_data ->> 'name', ''),
      split_part(new.email, '@', 1)
    ),
    new.email
  )
  on conflict (id) do update
    set email = excluded.email;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created_profile on auth.users;
create trigger on_auth_user_created_profile
after insert on auth.users
for each row execute procedure public.create_profile_for_user();

insert into public.profiles (id, display_name, email)
select
  id,
  coalesce(
    nullif(raw_user_meta_data ->> 'full_name', ''),
    nullif(raw_user_meta_data ->> 'name', ''),
    split_part(email, '@', 1)
  ),
  email
from auth.users
on conflict (id) do update
  set email = excluded.email;

create table if not exists public.products (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  sku text not null unique,
  category text not null check (category in ('Computers', 'Phones', 'Audio', 'Accessories', 'Gaming')),
  price numeric(12, 2) not null check (price >= 0),
  stock integer not null check (stock >= 0),
  photo_path text,
  tone text not null default '#e4e8ef',
  created_by uuid references public.profiles (id) on delete set null,
  updated_by uuid references public.profiles (id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.inventory_activity (
  id bigint generated by default as identity primary key,
  product_id uuid,
  product_name text not null,
  operation text not null check (operation in ('INSERT', 'UPDATE', 'DELETE')),
  before_data jsonb,
  after_data jsonb,
  actor_id uuid references public.profiles (id) on delete set null,
  occurred_at timestamptz not null default now()
);

create index if not exists inventory_activity_occurred_at_idx
  on public.inventory_activity (occurred_at desc);
create index if not exists inventory_activity_actor_id_idx
  on public.inventory_activity (actor_id);

alter table public.profiles enable row level security;
alter table public.products enable row level security;
alter table public.inventory_activity enable row level security;

