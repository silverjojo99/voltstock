create or replace function public.audit_product_changes()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if auth.uid() is null then
    if tg_op = 'DELETE' then
      return old;
    end if;
    return new;
  end if;

  if tg_op = 'INSERT' then
    new.created_by := auth.uid();
    new.updated_by := auth.uid();
    insert into public.inventory_activity (product_id, product_name, operation, after_data, actor_id)
    values (new.id, new.name, tg_op, to_jsonb(new), auth.uid());
    return new;
  elsif tg_op = 'UPDATE' then
    new.created_by := old.created_by;
    new.updated_by := auth.uid();
    new.created_at := old.created_at;
    new.updated_at := now();
    insert into public.inventory_activity (
      product_id, product_name, operation, before_data, after_data, actor_id
    )
    values (new.id, new.name, tg_op, to_jsonb(old), to_jsonb(new), auth.uid());
    return new;
  else
    insert into public.inventory_activity (product_id, product_name, operation, before_data, actor_id)
    values (old.id, old.name, tg_op, to_jsonb(old), auth.uid());
    return old;
  end if;
end;
$$;

drop trigger if exists products_audit_changes on public.products;
create trigger products_audit_changes
before insert or update or delete on public.products
for each row execute procedure public.audit_product_changes();

